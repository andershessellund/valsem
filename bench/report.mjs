// ---------------------------------------------------------------------------
// Render BENCHMARKS.md from bench/results/*.json (node and/or bun).
// ---------------------------------------------------------------------------
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const load = (name) => {
  const p = new URL(`./results/${name}.json`, import.meta.url);
  return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null;
};
const runs = [load('node'), load('bun')].filter(Boolean);
if (runs.length === 0) throw new Error('no results: run `node bench/run.mjs` (and `npx bun@latest bench/run.mjs`) first');

const fmtNs = (v) =>
  v === null || v === undefined ? '—' : v >= 1e6 ? `${(v / 1e6).toFixed(2)} ms` : v >= 1000 ? `${(v / 1000).toFixed(1)} µs` : `${v.toFixed(0)} ns`;
const fmtBytes = (v) => (v === null || v === undefined ? '—' : v >= 1024 ? `${(v / 1024).toFixed(1)} KB` : `${v} B`);
const fmtRatio = (num, den) => (num === null || den === null || num === undefined || den === undefined || den === 0 ? '—' : num >= den ? `${(num / den).toFixed(1)}×` : `1/${(den / num).toFixed(1)}×`);

const out = [];
out.push('# Benchmarks');
out.push('');
out.push('<!-- GENERATED by `pnpm bench` from bench/results/*.json — do not edit by hand. -->');
out.push('');
out.push(
  'Every number below is produced by `pnpm bench`, which runs the suites in `bench/suites/` on Node and on Bun ' +
    '(JavaScriptCore), writes one JSON file per runtime, and renders this file. Each section describes exactly what its ' +
    'suite measures. Cells show **node / bun**; a single value means the suite ran on one runtime. The rationale behind ' +
    'the designs these numbers reflect lives in [DECISIONS.md](DECISIONS.md).',
);
out.push('');
out.push('| | ' + runs.map((r) => `${r.runtime.name} ${r.runtime.version} (${r.runtime.engine})`).join(' | ') + ' |');
out.push('| --- | ' + runs.map(() => '---').join(' | ') + ' |');
out.push('| machine | ' + runs.map((r) => `${r.machine.cpu}, ${r.machine.platform}`).join(' | ') + ' |');
out.push('| date, commit | ' + runs.map((r) => `${r.date}, \`${r.commit}\``).join(' | ') + ' |');
out.push('| valsem | ' + runs.map((r) => r.valsem).join(' | ') + ' |');
out.push('| immer / mutative / immutable / fast-deep-equal | ' + runs.map((r) => `${r.libraries.immer} / ${r.libraries.mutative} / ${r.libraries.immutable} / ${r.libraries['fast-deep-equal']}`).join(' | ') + ' |');
out.push('');
out.push('Methodology, applied by every suite: results are retained where the honest regime requires it (discarded results ' +
  'die in the nursery and flatter copy-on-write libraries), each row asserts that contenders agree on the answer where ' +
  'there is one, fixtures are built in fast-properties mode (`Object.fromEntries`), and a novel state is produced per ' +
  'iteration unless the row says otherwise.');
out.push('');

const suiteIds = [];
for (const r of runs) for (const s of r.suites) if (!suiteIds.includes(s.id)) suiteIds.push(s.id);

for (const id of suiteIds) {
  const per = runs.map((r) => r.suites.find((s) => s.id === id) ?? null);
  const first = per.find(Boolean);
  out.push(`## ${first.title}`);
  out.push('');
  out.push(first.description.trim());
  out.push('');
  const fmt = first.unit === 'bytes' ? fmtBytes : first.unit === 'ns' ? fmtNs : (v) => (v === null || v === undefined ? '—' : String(v));
  const cols = first.columns;
  const ratio = first.ratio; // [numerator, denominator] column labels → an extra column
  const hasNotes = per.some((s) => s && s.rows.some((r) => r.note));
  const header = ['', ...cols, ...(ratio ? [`${ratio[1]} ÷ ${ratio[0]}`] : []), ...(hasNotes ? ['note'] : [])];
  out.push('| ' + header.join(' | ') + ' |');
  out.push('| ' + header.map(() => '---').join(' | ') + ' |');
  const rowNames = [];
  for (const s of per) if (s) for (const r of s.rows) if (!rowNames.includes(r.name)) rowNames.push(r.name);
  for (const name of rowNames) {
    const cells = [name];
    const rowsPer = per.map((s) => (s ? s.rows.find((r) => r.name === name) ?? null : null));
    for (const c of cols) {
      const vals = rowsPer.map((r) => (r ? r.values[c] : null));
      cells.push(vals.filter((v) => v !== null && v !== undefined).length === 0 ? '—' : vals.map(fmt).join(' / '));
    }
    if (ratio) {
      cells.push(rowsPer.map((r) => (r ? fmtRatio(r.values[ratio[1]], r.values[ratio[0]]) : '—')).join(' / '));
    }
    if (hasNotes) cells.push(rowsPer.map((r) => r?.note).find(Boolean) ?? '');
    out.push('| ' + cells.join(' | ') + ' |');
  }
  out.push('');
}

out.push('## Reproducing');
out.push('');
out.push('```bash');
out.push('pnpm build');
out.push('pnpm bench            # node, then bun, then this file');
out.push('node bench/run.mjs list memoize   # one or more suites, merged into the node results');
out.push('npx -y bun@latest bench/run.mjs  # the same on JavaScriptCore');
out.push('node bench/report.mjs            # re-render BENCHMARKS.md');
out.push('```');
out.push('');
out.push('The one-off experiments behind the decisions — pool cleanup strategies, retention regimes, the in-job WeakRef ' +
  'effect — live in `scripts/experiments/` and are referenced from [DECISIONS.md](DECISIONS.md).');
out.push('');
writeFileSync(new URL('../BENCHMARKS.md', import.meta.url), out.join('\n'));
console.log('wrote BENCHMARKS.md');
